// Command protocol maintains the S2 protobuf field ledger and generated sources.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"

	"github.com/thtpark/fdn/internal/message/payloadschema"
)

func main() {
	update := flag.Bool("update-fields", false, "append newly declared DTO fields/types to the explicit ledger, then rerun generation")
	check := flag.Bool("check", false, "check schema/field-ledger reproducibility without writing")
	flag.Parse()
	if err := run(*update, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(update, check bool) error {
	if update && check {
		return fmt.Errorf("choose --update-fields or --check")
	}
	entries, err := os.ReadDir("internal/domain")
	if err != nil {
		return err
	}
	structs := make(map[string]*ast.StructType)
	for _, entry := range entries {
		if !strings.HasSuffix(entry.Name(), ".go") || strings.HasSuffix(entry.Name(), "_test.go") {
			continue
		}
		file, err := parser.ParseFile(token.NewFileSet(), filepath.Join("internal/domain", entry.Name()), nil, 0)
		if err != nil {
			return err
		}
		for _, declaration := range file.Decls {
			generic, ok := declaration.(*ast.GenDecl)
			if !ok {
				continue
			}
			for _, specification := range generic.Specs {
				spec, ok := specification.(*ast.TypeSpec)
				if !ok || spec.TypeParams != nil {
					continue
				}
				if st, ok := spec.Type.(*ast.StructType); ok {
					structs[spec.Name.Name] = st
				}
			}
		}
	}
	ledger := payloadschema.Numbers()
	names := make([]string, 0, len(structs))
	for name := range structs {
		names = append(names, name)
	}
	slices.Sort(names)
	for _, name := range names {
		if ledger[name] == nil {
			ledger[name] = make(map[string]payloadschema.Number)
		}
		next := int32(1)
		for _, number := range ledger[name] {
			if number.ID >= next {
				next = number.ID + 1
			}
		}
		var visit func(*ast.StructType) error
		visit = func(st *ast.StructType) error {
			for _, field := range st.Fields.List {
				if len(field.Names) == 0 {
					ident, ok := field.Type.(*ast.Ident)
					if !ok || structs[ident.Name] == nil {
						return fmt.Errorf("unsupported embedded DTO field")
					}
					if err := visit(structs[ident.Name]); err != nil {
						return err
					}
					continue
				}
				if field.Tag == nil || len(field.Names) != 1 {
					return fmt.Errorf("DTO fields require one explicit JSON/protobuf name")
				}
				tag := strings.Trim(field.Tag.Value, "`")
				protoName := ""
				// go/parser retains the quoted struct tag; extracting its JSON name
				// uses the same grammar as reflect.StructTag, not payload JSON.
				if at := strings.Index(tag, `json:"`); at >= 0 {
					protoName = strings.Split(strings.Split(tag[at+6:], `"`)[0], ",")[0]
				}
				if protoName == "" || protoName == "-" {
					return fmt.Errorf("unsupported DTO field tag")
				}
				goName := field.Names[0].Name
				number, exists := ledger[name][goName]
				if exists {
					if number.Name != protoName {
						return fmt.Errorf("protobuf field rename requires a new contract: %s.%s", name, goName)
					}
				} else {
					if next >= 19000 && next <= 19999 {
						next = 20000
					}
					ledger[name][goName] = payloadschema.Number{ID: next, Name: protoName}
					next++
				}
			}
			return nil
		}
		if err := visit(structs[name]); err != nil {
			return err
		}
	}
	jsonData, err := json.MarshalIndent(ledger, "", "  ")
	if err != nil {
		return err
	}
	jsonData = append(jsonData, '\n')
	var types bytes.Buffer
	types.WriteString("// Code generated by tools/protocol; DO NOT EDIT.\npackage payloadschema\n\n")
	types.WriteString("import (\n\"reflect\"\n\"github.com/thtpark/fdn/internal/domain\"\n)\n\nvar Types = []reflect.Type{\n")
	for _, name := range names {
		fmt.Fprintf(&types, "reflect.TypeFor[domain.%s](),\nreflect.TypeFor[domain.Page[domain.%s]](),\n", name, name)
	}
	types.WriteString("}\n")
	typeData, err := format.Source(types.Bytes())
	if err != nil {
		return err
	}
	for path, data := range map[string][]byte{
		"internal/message/payloadschema/fields.json": jsonData,
		"internal/message/payloadschema/types.go":    typeData,
	} {
		if update {
			if err := os.WriteFile(path, data, 0644); err != nil {
				return err
			}
		} else if existing, err := os.ReadFile(path); err != nil || !bytes.Equal(existing, data) {
			return fmt.Errorf("%s is stale; run --update-fields then rerun generation", path)
		}
	}
	if update {
		fmt.Println("Field ledger updated; rerun go run ./tools/protocol to compile the new mapping.")
		return nil
	}
	contract, err := payloadschema.Contract()
	if err != nil {
		return err
	}
	path := "internal/message/payload.proto"
	if check {
		existing, err := os.ReadFile(path)
		if err != nil || string(existing) != contract {
			return fmt.Errorf("%s is stale", path)
		}
	} else {
		if err := os.WriteFile(path, []byte(contract), 0644); err != nil {
			return err
		}
	}
	version, err := exec.Command("protoc", "--version").Output()
	if err != nil || strings.TrimSpace(string(version)) != "libprotoc 36.2" {
		return fmt.Errorf("generation requires protoc 36.2")
	}
	work := "tools/protocol/.work"
	if err := os.Mkdir(work, 0700); err != nil {
		return err
	}
	defer os.RemoveAll(work)
	plugin, err := filepath.Abs(filepath.Join(work, "protoc-gen-go"))
	if err != nil {
		return err
	}
	build := exec.Command("go", "build", "-o", plugin, "google.golang.org/protobuf/cmd/protoc-gen-go")
	build.Stdout, build.Stderr = os.Stdout, os.Stderr
	if err := build.Run(); err != nil {
		return err
	}
	output := "."
	if check {
		output = work
	}
	command := exec.Command("protoc", "--plugin=protoc-gen-go="+plugin, "--go_out="+output,
		"--go_opt=module=github.com/thtpark/fdn", "internal/message/wire.proto")
	command.Stdout, command.Stderr = os.Stdout, os.Stderr
	if err := command.Run(); err != nil {
		return err
	}
	command = exec.Command("protoc", "--descriptor_set_out="+filepath.Join(work, "payload.pb"), path)
	command.Stdout, command.Stderr = os.Stdout, os.Stderr
	if err := command.Run(); err != nil {
		return err
	}
	if check {
		path := "internal/message/wire/wire.pb.go"
		existing, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		generated, err := os.ReadFile(filepath.Join(work, path))
		if err != nil || !bytes.Equal(existing, generated) {
			return fmt.Errorf("%s is stale", path)
		}
	}
	return nil
}
